"""Real-time Security Webhook Alerting for Slack, Discord, and SecOps.

Translates RedCell audit reports into rich notifications:
- Slack Block Kit formatted alert cards
- Discord Rich Embeds with color-coded severity
- Generic JSON webhook payloads for SIEM/SOAR ingestion
- Standard library urllib HTTP dispatch with timeout resilience
"""
from __future__ import annotations

import json
import os
import sys
import urllib.error
import urllib.request
from typing import Any

COLOR_RED = 0xD9002B    # 14221355 (breach)
COLOR_GREEN = 0x2F7D32  # 3112242 (passed)


def detect_webhook_type(url: str) -> str:
    """Detect destination service based on webhook URL pattern."""
    u = url.lower()
    if "hooks.slack.com" in u:
        return "slack"
    if "discord.com/api/webhooks" in u or "discordapp.com/api/webhooks" in u:
        return "discord"
    return "generic"


def build_slack_payload(report_data: dict[str, Any]) -> dict[str, Any]:
    """Format RedCell report as Slack Block Kit message."""
    target_name = report_data.get("target", "AI Agent")
    hardened = report_data.get("target_hardened", False)
    broken = report_data.get("goals_broken", 0)
    tried = report_data.get("goals_tried", 0)
    findings = report_data.get("findings", [])
    usage = report_data.get("usage", {})
    cost = usage.get("cost_usd", 0.0)

    if broken > 0:
        headline = f"🚨 *RedCell Security Alert: {broken} of {tried} Goals Compromised*"
        color = "#D9002B"
    else:
        headline = f"✅ *RedCell Audit Passed: All {tried} Defense Goals Held*"
        color = "#2F7D32"

    blocks = [
        {
            "type": "section",
            "text": {"type": "mrkdwn", "text": headline},
        },
        {
            "type": "section",
            "fields": [
                {"type": "mrkdwn", "text": f"*Target:*\n{target_name} ({'hardened' if hardened else 'standard'})"},
                {"type": "mrkdwn", "text": f"*Evaluator Engine:*\nNVIDIA Nemotron on Nebius"},
                {"type": "mrkdwn", "text": f"*Defense Rate:*\n{int(((tried - broken) / max(1, tried)) * 100)}%"},
                {"type": "mrkdwn", "text": f"*Spend:*\n${cost:.4f}"},
            ],
        },
    ]

    if findings:
        findings_lines = []
        for f in findings[:5]:
            findings_lines.append(f"• *{f.get('title')}* (`{f.get('owasp', '')}`): {f.get('evidence', '')}")
        blocks.append({
            "type": "section",
            "text": {"type": "mrkdwn", "text": "*Confirmed Vulnerabilities:*\n" + "\n".join(findings_lines)},
        })

    blocks.append({
        "type": "context",
        "elements": [
            {"type": "mrkdwn", "text": "Generated by *RedCell* · OWASP Top 10 for LLMs · NVIDIA NeMo Guardrails Ready"}
        ],
    })

    return {
        "text": headline,
        "attachments": [{"color": color, "blocks": blocks}],
    }


def build_discord_payload(report_data: dict[str, Any]) -> dict[str, Any]:
    """Format RedCell report as Discord Rich Embed."""
    target_name = report_data.get("target", "AI Agent")
    hardened = report_data.get("target_hardened", False)
    broken = report_data.get("goals_broken", 0)
    tried = report_data.get("goals_tried", 0)
    findings = report_data.get("findings", [])
    usage = report_data.get("usage", {})
    cost = usage.get("cost_usd", 0.0)

    if broken > 0:
        title = f"🚨 RedCell Security Alert: {broken} Goals Broken"
        color = COLOR_RED
        desc = f"Adversarial red-teaming detected **{broken} confirmed vulnerabilities** on `{target_name}`."
    else:
        title = f"✅ RedCell Audit Passed: All Defenses Held"
        color = COLOR_GREEN
        desc = f"Candidate agent `{target_name}` resisted all {tried} multi-turn attack goals."

    fields = [
        {"name": "Target Agent", "value": target_name, "inline": True},
        {"name": "Status", "value": "Hardened" if hardened else "Standard", "inline": True},
        {"name": "Defense Rate", "value": f"{int(((tried - broken) / max(1, tried)) * 100)}%", "inline": True},
        {"name": "Evaluation Engine", "value": "NVIDIA Nemotron Ultra / Nano", "inline": True},
        {"name": "Total Spend", "value": f"${cost:.4f}", "inline": True},
        {"name": "Goals Broken", "value": f"{broken} / {tried}", "inline": True},
    ]

    for f in findings[:4]:
        fields.append({
            "name": f"🔴 {f.get('title')}",
            "value": f"**Proof:** {f.get('evidence')}\n**Fix:** {f.get('fix')[:120]}...",
            "inline": False,
        })

    embed = {
        "title": title,
        "description": desc,
        "color": color,
        "fields": fields,
        "footer": {"text": "RedCell · Autonomous Agent Security · Nebius Token Factory"},
    }

    return {"embeds": [embed]}


def build_generic_payload(report_data: dict[str, Any]) -> dict[str, Any]:
    """Universal payload for SIEM/SOAR or webhook gateways."""
    broken = report_data.get("goals_broken", 0)
    return {
        "event": "redcell.audit.completed",
        "status": "compromised" if broken > 0 else "defended",
        "target": report_data.get("target"),
        "target_hardened": report_data.get("target_hardened", False),
        "goals_broken": broken,
        "goals_tried": report_data.get("goals_tried", 0),
        "findings": report_data.get("findings", []),
        "usage": report_data.get("usage", {}),
        "text": f"RedCell evaluation complete: {broken} of {report_data.get('goals_tried', 0)} goals broken.",
    }


def send_webhook_alert(
    report_data: dict[str, Any],
    webhook_url: str | None = None,
    timeout: int = 10,
) -> bool:
    """Dispatch real-time webhook alert to Slack, Discord, or generic endpoint.

    Returns True if successfully dispatched, False otherwise. Never raises exceptions.
    """
    url = webhook_url or os.environ.get("REDCELL_WEBHOOK_URL")
    if not url:
        return False

    wtype = detect_webhook_type(url)
    if wtype == "slack":
        payload = build_slack_payload(report_data)
    elif wtype == "discord":
        payload = build_discord_payload(report_data)
    else:
        payload = build_generic_payload(report_data)

    data = json.dumps(payload).encode("utf-8")
    req = urllib.request.Request(
        url,
        data=data,
        headers={"Content-Type": "application/json", "User-Agent": "RedCell-Alert-Bot/1.0"},
        method="POST",
    )

    try:
        with urllib.request.urlopen(req, timeout=timeout) as resp:
            return 200 <= resp.status < 300
    except Exception as e:
        print(f"Warning: Failed to deliver webhook alert ({url}): {e}", file=sys.stderr)
        return False


def main() -> int:
    import argparse
    ap = argparse.ArgumentParser(description="RedCell Real-Time Security Webhook Alert Dispatcher")
    ap.add_argument("--report", type=str, default=None, help="Path to report JSON")
    ap.add_argument("--webhook", type=str, default=None, help="Slack or Discord webhook URL")
    ap.add_argument("--dry-run", action="store_true", help="Print payload without sending")
    args = ap.parse_args()

    # Find report file
    report_path = args.report
    if not report_path:
        for c in [
            os.path.join(os.path.dirname(__file__), "..", "..", "reports", "report.json"),
            os.path.join(os.path.dirname(__file__), "..", "..", "web", "last-live", "report.json"),
        ]:
            if os.path.exists(c):
                report_path = c
                break

    if not report_path or not os.path.exists(report_path):
        print("Error: Could not locate report JSON.", file=sys.stderr)
        return 1

    with open(report_path, "r", encoding="utf-8") as f:
        report_data = json.load(f)

    webhook_url = args.webhook or os.environ.get("REDCELL_WEBHOOK_URL")
    if not webhook_url and not args.dry_run:
        print("Error: Webhook URL required (specify --webhook or set REDCELL_WEBHOOK_URL).", file=sys.stderr)
        return 1

    if args.dry_run:
        wtype = detect_webhook_type(webhook_url or "https://hooks.slack.com")
        if wtype == "slack":
            p = build_slack_payload(report_data)
        elif wtype == "discord":
            p = build_discord_payload(report_data)
        else:
            p = build_generic_payload(report_data)
        print(json.dumps(p, indent=2))
        return 0

    ok = send_webhook_alert(report_data, webhook_url)
    if ok:
        print(f"Successfully dispatched alert to {webhook_url}")
        return 0
    else:
        print("Failed to dispatch alert.", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
