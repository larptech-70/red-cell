def to_guardrails_bundle(report_data: dict[str, Any]) -> dict[str, str]:
    """Compile all NeMo Guardrails configuration files into a filename-to-content dict."""
    return {
        "config.yml": generate_config_yaml(report_data),
        "prompts.yml": generate_prompts_yaml(),
        "rails.co": generate_colang_rails(report_data),
        "actions.py": generate_actions_py(report_data),
        "README.md": generate_readme(report_data),
    }


def export_guardrails(
    report_data: dict[str, Any],
    outdir: str | pathlib.Path = "reports/guardrails",
) -> dict[str, str]:
    """Write all NeMo Guardrails configuration files to disk."""
    out_path = pathlib.Path(outdir)
    out_path.mkdir(parents=True, exist_ok=True)

    bundle = to_guardrails_bundle(report_data)
    written: dict[str, str] = {}

    for fname, content in bundle.items():
        file_path = out_path / fname
        file_path.write_text(content, encoding="utf-8")
        written[fname] = str(file_path.resolve())

    return written


def to_zip_bytes(report_data: dict[str, Any]) -> bytes:
    """Package the NeMo Guardrails bundle into in-memory zip bytes."""
    bundle = to_guardrails_bundle(report_data)
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as zf:
        for fname, content in bundle.items():
            zf.writestr(f"guardrails/{fname}", content)
    buf.seek(0)
    return buf.getvalue()


def export_zip(
    report_data: dict[str, Any],
    zip_path: str | pathlib.Path = "reports/guardrails.zip",
) -> str:
    """Export the NeMo Guardrails bundle to a .zip archive on disk."""
    p = pathlib.Path(zip_path)
    p.parent.mkdir(parents=True, exist_ok=True)
    zip_bytes = to_zip_bytes(report_data)
    p.write_bytes(zip_bytes)
    return str(p.resolve())

